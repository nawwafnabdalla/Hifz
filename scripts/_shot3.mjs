import { chromium, devices } from '@playwright/test'
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
const p = await (await b.newContext({ ...devices['Pixel 7'], viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })).newPage()
await p.goto('http://localhost:4173/quran/2'); await p.waitForTimeout(800)
await p.getByRole('button', { name: 'Mushaf' }).click()
await p.goto('http://localhost:4173/quran/2?a=255'); await p.waitForTimeout(1500)
await p.getByRole('button', { name: 'Mushaf' }).click()
await p.waitForTimeout(600)
await p.locator('[data-ayah="255"]').first().scrollIntoViewIfNeeded()
await p.locator('p.arabic').first().screenshot({ path: 'test-results/shots/30-kursi-text.png' }).catch(()=>{})
await p.screenshot({ path: 'test-results/shots/30b-kursi-page.png' })
await b.close()
