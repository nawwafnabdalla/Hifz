import { chromium } from '@playwright/test'
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage()
p.on('pageerror', e => console.log('PAGEERROR', e.message))
await p.goto('http://localhost:4173/quran/112')
await p.waitForTimeout(500)
await p.getByRole('listitem', { name: /^Ayah 1:/ }).click()
await p.getByRole('listitem', { name: /^Ayah 3:/ }).click()
await p.waitForTimeout(300)
console.log(await p.getByTestId('selection-bar').count(), await p.getByTestId('selection-bar').innerText().catch(()=>'none'))
await p.screenshot({ path: 'test-results/shots/dbg.png' })
await b.close()
