// Regenerates docs/PHRASE_GALLERY.md from the engine as shipped:  GALLERY=1 npx vitest run tests/gallery.gen.test.ts
import { describe, it } from 'vitest'
import { writeFileSync } from 'node:fs'
import { wordsOfAyah } from '@/lib/quran/data'
import { buildPhrases } from '@/lib/engine/phrases'
import { candidatesFor, defaultBreakdown } from '@/lib/engine/breakdown'
import review from '@/data/phrase-review.json'

const CASES: [number, number, string][] = [
  [20, 40, 'long narrative, three printed signs'], [20, 71, 'five clauses, no printed signs'], [20, 86, 'dialogue with a question (provisional, see note)'],
  [20, 97, 'verb and its complement must stay together'], [20, 53, 'a list of divine acts'], [20, 130, 'commands in sequence'], [20, 94, 'speech with a sub-clause'],
  [20, 47, 'imperatives and a closing'], [2, 255, 'Ayat al-Kursi: heavy printed guidance'], [2, 282, 'the longest ayah (128 words)'], [2, 177, 'a long enumerated ayah'],
  [3, 190, 'two-clause ayah'], [18, 9, 'short: stays whole'], [20, 2, 'very short: stays whole'],
]
describe.skipIf(!process.env.GALLERY)('gallery', () => {
  it('writes docs/PHRASE_GALLERY.md', () => {
    let md = `# Phrase gallery: automatic practice phrases for hard cases\n\nGenerated by the shipped engine (\`defaultBreakdown\`, spelling-based model, no reciter timing). **For a qualified reader to review.** Each break shows its evidence; none is a place to stop when reciting. Breaks a reviewer has rejected are recorded in \`src/data/phrase-review.json\` and honoured by the engine.\n\n`
    for (const [s, a, title] of CASES) {
      const w = wordsOfAyah(s, a), b = defaultBreakdown(s, a, w), ph = buildPhrases(w, b.boundaries), p = new Map(candidatesFor(s, a, w.length).map((c) => [c.after, c.p]))
      const led = (review as { ayahs?: Record<string, { status: string; rejected?: number[]; note?: string }> }).ayahs?.[`${s}:${a}`] ?? (review as Record<string, unknown>)[`${s}:${a}`] as { status: string; rejected?: number[]; note?: string } | undefined
      md += `## ${s}:${a}: ${title}\n${w.length} words → ${ph.length === 1 ? 'learned whole' : `${ph.length} phrases`}\n\n`
      ph.forEach((x, i) => { const at = b.boundaries[i]; md += `${i + 1}. \`${x.words.join(' ')}\` (${x.words.length} words)${at !== undefined ? ` — break after: ${b.basis[at]}${p.has(at) ? `, p=${p.get(at)!.toFixed(2)}` : ''}` : ''}\n` })
      if (led && typeof led === 'object' && 'status' in led) md += `\n_Review ledger: ${led.status}${led.rejected?.length ? `; rejected break(s) after word ${led.rejected.map((x) => x + 1).join(', ')}` : ''}. ${led.note ?? ''}_\n`
      md += '\n'
    }
    writeFileSync('docs/PHRASE_GALLERY.md', md)
  })
})
